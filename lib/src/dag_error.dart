/// Thrown by a generated `dag` render function when a `<?dag= ?>`
/// expression (or the literal text around it) throws. Wraps the original
/// error with the `.dag` source location that produced the offending line
/// of generated code, so a stack trace pointing into `foo.g.dart` doesn't
/// have to be translated back to `foo.dag` by hand.
class DagError extends Error {
  final String sourcePath;
  final int line;
  final Object error;
  final StackTrace sourceStackTrace;

  DagError(this.sourcePath, this.line, this.error, this.sourceStackTrace);

  @override
  String toString() =>
      'DagError: $error\n  at $sourcePath:$line (generated by package:dag)';
}
