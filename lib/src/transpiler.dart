import 'lexer.dart';
import 'nodes.dart';

/// Transpiles .dag [source] into a standalone .dart source string.
///
/// [sourcePath] is only used for the "Source:" comment in the generated
/// header; it has no effect on behavior.
String transpile(String source, {String sourcePath = ''}) {
  final nodes = lex(source);

  final imports = <String>[];
  String? params;
  String functionName = 'render';

  for (final n in nodes) {
    switch (n) {
      case ImportsNode():
        for (final rawLine in n.code.split('\n')) {
          final t = rawLine.trim();
          if (t.isEmpty) continue;
          final stmt = t.endsWith(';') ? t : '$t;';
          if (!imports.contains(stmt)) imports.add(stmt);
        }
      case ParamsNode():
        if (n.code.isNotEmpty) {
          params = params == null ? n.code : '$params, ${n.code}';
        }
      case NameNode():
        if (n.code.isNotEmpty) functionName = n.code;
      case TextNode():
      case EchoNode():
      case CodeNode():
        break;
    }
  }

  final displayPath = sourcePath.isEmpty ? 'unknown' : sourcePath;
  final pathLiteral = _escapeForDoubleQuotedString(displayPath);

  final out = StringBuffer();
  out.writeln('// GENERATED CODE — do not edit by hand.');
  out.writeln(
      '// Generated by package:dag from${sourcePath.isEmpty ? '' : ' $sourcePath'}');
  out.writeln('// ignore_for_file: type=lint');
  out.writeln();
  out.writeln("import 'package:dag/dag.dart' show DagError;");
  for (final imp in imports) {
    out.writeln(imp);
  }
  out.writeln();

  out.writeln('Future<String> $functionName(${params ?? ''}) async {');
  out.writeln('  final _buf = StringBuffer();');
  out.writeln('  var _dagLine = 0;');
  out.writeln('  try {');

  final pending = StringBuffer();
  int? pendingLine;
  void flushPending() {
    if (pending.isEmpty) return;
    out.writeln('    _dagLine = $pendingLine;');
    out.writeln('    _buf.write("${pending.toString()}");');
    pending.clear();
    pendingLine = null;
  }

  for (final n in nodes) {
    switch (n) {
      case TextNode():
        pendingLine ??= n.line;
        pending.write(_escapeForDoubleQuotedString(n.text));
      case EchoNode():
        if (n.expr.isEmpty) {
          throw FormatException('Empty <?dag= ?> expression at line ${n.line}');
        }
        // Flushed on its own so a failing expression is blamed for its own
        // line, not the start of whatever text run it happens to sit in.
        flushPending();
        out.writeln('    _dagLine = ${n.line};');
        out.writeln('    _buf.write("\${${n.expr}}");');
      case CodeNode():
        final code = n.code.trim();
        if (code.isEmpty) continue;
        flushPending();
        out.writeln('    _dagLine = ${n.line};');
        out.writeln('    $code');
      case ImportsNode():
      case ParamsNode():
      case NameNode():
        break;
    }
  }
  flushPending();

  out.writeln('  } catch (e, st) {');
  out.writeln('    throw DagError("$pathLiteral", _dagLine, e, st);');
  out.writeln('  }');
  out.writeln('  return _buf.toString();');
  out.writeln('}');

  return out.toString();
}

/// Escapes text so it can sit inside a Dart double-quoted, non-raw string
/// literal without accidentally starting an interpolation, terminating the
/// string early, or embedding a literal (unescaped) newline.
String _escapeForDoubleQuotedString(String text) {
  final b = StringBuffer();
  for (final rune in text.runes) {
    switch (rune) {
      case 0x5C: // backslash
        b.write(r'\\');
      case 0x24: // $
        b.write(r'\$');
      case 0x22: // "
        b.write(r'\"');
      case 0x0A: // \n
        b.write(r'\n');
      case 0x0D: // \r
        break; // normalize CRLF -> LF
      default:
        b.writeCharCode(rune);
    }
  }
  return b.toString();
}
